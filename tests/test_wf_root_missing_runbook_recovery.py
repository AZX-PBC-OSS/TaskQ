def _extract_remedy_span(doc: str) -> str:
    """The ordered-list item 3 span of the stranded-jobs 'How to remediate.'
    list — from its own ``3.`` line to the next column-0 ``4.`` line."""
    lines = doc.splitlines()
    starts = [i for i, ln in enumerate(lines) if ln.startswith("3. `workflow_root_missing`")]
    assert len(starts) == 1, (
        f"expected exactly one workflow_root_missing item line, got {len(starts)}"
    )
    start = starts[0]
    ends = [i for i in range(start + 1, len(lines)) if lines[i].startswith("4. ")]
    assert ends, "the remediation list's item 4 is missing (a column-0 paste broke the list)"
    end = ends[0]
    return "\n".join(lines[start:end])


def _extract_remedy_sql(doc: str) -> str:
    """The item-3 span's ONE ```sql fenced block (the doc's own bytes)."""
    span = _extract_remedy_span(doc)
    fence_opens = [i for i, ln in enumerate(span.splitlines()) if ln.strip() == "```sql"]
    assert len(fence_opens) == 1, (
        f"expected exactly one ```sql fence inside the workflow_root_missing item, "
        f"got {len(fence_opens)}"
    )
    lines = span.splitlines()
    open_idx = fence_opens[0]
    closes = [i for i in range(open_idx + 1, len(lines)) if lines[i].strip() == "```"]
    assert closes, "the remedy's sql fence is never closed"
    return "\n".join(lines[open_idx + 1 : closes[0]])


def _split_sql_aware(sql: str) -> list[str]:
    """Split on statement semicolons OUTSIDE single-quoted literals and
    line comments (the remedy's error_message literal carries an embedded
    semicolon — a naive split cuts mid-literal)."""
    statements: list[str] = []
    current: list[str] = []
    in_quote = False
    i = 0
    while i < len(sql):
        ch = sql[i]
        if ch == "'" and not in_quote:
            in_quote = True
            current.append(ch)
        elif ch == "'" and in_quote:
            # '' is the escaped quote (stay in the literal); a single '
            # closes it.
            if i + 1 < len(sql) and sql[i + 1] == "'":
                current.append("''")
                i += 1
            else:
                in_quote = False
                current.append(ch)
        elif ch == "-" and not in_quote and sql[i : i + 2] == "--":
            j = sql.find("\n", i)
            j = len(sql) if j == -1 else j
            current.append(sql[i:j])
            i = j
            continue
        elif ch == ";" and not in_quote:
            statements.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
        i += 1
    tail = "".join(current).strip()
    if tail:
        statements.append(tail)
    assert not in_quote, "the splitter left an unterminated string literal (drifted doc bytes)"
    return [s for s in statements if s]


def _transform_for_test(sql: str, flow_id: str, schema: str) -> list[str]:
    """The document bytes' test-face transformation (C3.3): drop the single
    ``\\set``, substitute every ``:'flow_id'``, rewrite ``taskq.`` to the
    validated test schema, fail closed on any surviving psql token."""
    assert sql.count("\\set") == 1, (
        "expected exactly one psql \\set line in the remedy (drifted doc bytes)"
    )
    lines = [ln for ln in sql.splitlines() if not ln.strip().startswith("\\set")]
    out = "\n".join(lines)
    occurrences = out.count(":'flow_id'")
    assert occurrences == 4, (
        f"expected exactly four :'flow_id' occurrences in the remedy, got {occurrences}"
    )
    out = out.replace(":'flow_id'", f"'{flow_id}'")
    assert "taskq." in out, "the remedy lost its schema-qualified names (drifted doc bytes)"
    out = out.replace("taskq.", f'"{schema}".')
    # Fail closed on surviving psql tokens: any backslash command, and any
    # single-colon variable (':'name'', :name, :"name") — while never
    # misclassifying PostgreSQL's ::type casts.
    for lineno, ln in enumerate(out.splitlines(), 1):
        assert not ln.strip().startswith("\\"), f"surviving psql command at +{lineno}: {ln!r}"
    import re

    var_re = re.compile(r"(?<!:):(?!:)['\"A-Za-z_]")
    survivors = [
        f"+{lineno}: {ln!r}" for lineno, ln in enumerate(out.splitlines(), 1) if var_re.search(ln)
    ]
    assert not survivors, f"surviving psql variable tokens in the transformed remedy: {survivors}"
    statements = _split_sql_aware(out)
    begins = [s for s in statements if s.upper() == "BEGIN"]
    commits = [s for s in statements if s.upper() == "COMMIT"]
    assert len(begins) == 1 and len(commits) == 1, (
        f"expected exactly one BEGIN and one COMMIT in the remedy, got {len(begins)}/{len(commits)}"
    )
    return [s for s in statements if s.upper() not in ("BEGIN", "COMMIT")]


async def _seed_orphan(
    conn: asyncpg.Connection,
    schema: str,
    flow_id: str,
    *,
    status: str,
    step_key: str,
    map_index: int | None,
    claim_epoch: int = 0,
    extra_meta: dict[str, Any] | None = None,
) -> str:
    """One orphan-shaped non-root row for *flow_id*."""
    from taskq._ids import new_uuid

    job_id = str(new_uuid())
    meta: dict[str, Any] = {"flow_id": flow_id}
    if extra_meta:
        meta.update(extra_meta)
    await conn.execute(
        f'INSERT INTO "{schema}".jobs (id, actor, queue, payload, status, attempt, '
        "max_attempts, retry_kind, step_key, map_index, claim_epoch, metadata, "
        "scheduled_at, created_at, finished_at, fairness_key, assignment_routed, "
        "idempotency_scope, idempotency_key) VALUES ($1, 'r17', 'default', '{}', "
        f"$2::text::\"{schema}\".job_status, $3, 3, 'transient', $4, $5::smallint, "
        "$9::bigint, $6::jsonb, clock_timestamp(), clock_timestamp(), NULL, $7, true, "
        "'workflow-run', $8)",
        job_id,
        status,
        2 if status == "running" else 0,
        step_key,
        map_index,
        _json.dumps(meta),
        flow_id,
        f"wf:{flow_id}:{step_key}:{job_id}",
        claim_epoch,
    )
    return job_id


async def _seed_ledger(
    conn: asyncpg.Connection,
    schema: str,
    flow_id: str,
    job_id: str,
    *,
    step_key: str,
    map_index: int | None,
    attempt: int,
    claim_epoch: int,
    status: str,
) -> str:
    from taskq._ids import new_uuid

    ledger_id = str(new_uuid())
    await conn.execute(
        f'INSERT INTO "{schema}".wf_step_ledger (id, flow_id, job_id, step_key, '
        "map_index, attempt, claim_epoch, status, created_at, updated_at) "
        "VALUES ($1, $2, $3, $4, $5::smallint, $6::int, $7::bigint, $8::text, "
        "clock_timestamp(), clock_timestamp())",
        ledger_id,
        flow_id,
        job_id,
        step_key,
        map_index,
        attempt,
        claim_epoch,
        status,
    )
    return ledger_id


